export const articleById = (id) => HELP_ARTICLES.find((article) => article.id === id) ?? null;

export const categoryById = (id) => HELP_CATEGORIES.find((category) => category.id === id) ?? null;

export const articlesIn = (categoryId) =>
  HELP_ARTICLES.filter((article) => article.category === categoryId);

export const videoById = (id) => TUTORIAL_VIDEOS.find((video) => video.id === id) ?? null;

export const videoForArticle = (articleId) =>
  TUTORIAL_VIDEOS.find((video) => video.articleId === articleId) ?? null;

export function categoryCount(category) {
  if (category.kind === "videos") return TUTORIAL_VIDEOS.length;
  if (category.kind === "troubleshooting") return TROUBLESHOOTING_ITEMS.length + FAQ_ITEMS.length;
  if (category.kind === "onboarding") return ONBOARDING_STAGES.length;
  return articlesIn(category.id).length;
}

export function categoryCountLabel(category) {
  const count = categoryCount(category);
  const noun =
    category.kind === "videos"
      ? "video"
      : category.kind === "troubleshooting"
        ? "answer"
        : category.kind === "onboarding"
          ? "stage"
          : "guide";
  return `${count} ${noun}${count === 1 ? "" : "s"}`;
}

function matches(text, terms) {
  const haystack = text.join(" ").toLowerCase();
  return terms.every((term) => haystack.includes(term));
}

export function searchHelp(query) {
  const terms = String(query ?? "").toLowerCase().trim().split(/\s+/).filter(Boolean);
  if (!terms.length) return [];
  const results = [];

  for (const article of HELP_ARTICLES) {
    const text = [
      article.title,
      article.summary,
      categoryById(article.category)?.label ?? "",
      ...article.overview,
      ...article.before,
      ...article.steps.flatMap((step) => [step.title, step.detail]),
      ...(article.more?.steps ?? []).flatMap((step) => [step.title, step.detail]),
      ...(article.tips ?? []),
      ...(article.issues ?? []).flatMap((issue) => [issue.problem, issue.fix]),
    ];
    if (matches(text, terms)) {
      results.push({
        kind: "article",
        id: article.id,
        title: article.title,
        summary: article.summary,
        meta: `${categoryById(article.category)?.label} · ${article.minutes} min read`,
      });
    }
  }

  for (const video of TUTORIAL_VIDEOS) {
    const text = [
      video.title,
      video.description,
      video.track,
      ...video.scenes.flatMap((scene) => [scene.title, scene.caption, scene.transcript]),
    ];
    if (matches(text, terms)) {
      results.push({
        kind: "video",
        id: video.id,
        title: video.title,
        summary: video.description,
        meta: `Video ${video.number} · ${video.duration}`,
      });
    }
  }

  for (const item of TROUBLESHOOTING_ITEMS) {
    if (matches([item.issue, item.summary, item.category, ...item.steps], terms)) {
      results.push({
        kind: "fix",
        id: item.id,
        title: item.issue,
        summary: item.summary,
        meta: `Troubleshooting · ${item.category}`,
      });
    }
  }

  for (const faq of FAQ_ITEMS) {
    if (matches([faq.question, faq.answer], terms)) {
      results.push({ kind: "faq", id: faq.id, title: faq.question, summary: faq.answer, meta: "FAQ" });
    }
  }

  return results;
}